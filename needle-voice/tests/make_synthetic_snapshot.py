#!/usr/bin/env python3
"""Builds real_snapshot.json: a SYNTHETIC home used by the tests (the file name is historical; it no longer describes any real household).

It keeps only the entities the tests depend on (generic kitchen / living-room / pool names) and adds generic filler so retrieval still has look-alikes
to sort through. Regenerate with:  python3 make_synthetic_snapshot.py > real_snapshot.json  (output is deterministic).
"""
import json

areas = [("kitchen", "Kitchen"), ("living_room", "Living Room"), ("swimming_pool", "Swimming Pool"), ("guest_room", "Guest Room"),
         ("basement", "Basement"), ("bedroom_1", "Bedroom One"), ("bedroom_2", "Bedroom Two"), ("bathroom", "Bathroom"), ("garage", "Garage"),
         ("garden", "Garden"), ("office", "Office"), ("hallway", "Hallway")]

E = []  # (entity_id, name, area)


def add(eid, name, area=None):
    E.append({"entity_id": eid, "name": name, "aliases": [], "area_id": area})


# ---- entities the tests rely on (names are generic home vocabulary)
add("light.kitchen_recessed_light_1", "Kitchen Recessed Light 1", "kitchen")
add("media_player.living_room_tv", "Living Room TV", "living_room")
add("climate.living_room_thermostat", "Living Room Thermostat", "living_room")
add("sensor.living_room_thermostat_temperature", "Living Room Thermostat Temperature", "living_room")
add("light.guest_room_lamp_1", "Guest Room Lamp 1", "guest_room")
add("media_player.basement_tv", "Basement TV", "basement")
add("fan.pool_fan", "Pool Fan", "swimming_pool")
add("switch.pool_pendant_lights", "Pool Pendant Lights", "swimming_pool")
add("switch.pool_high_bay_lights", "Pool High Bay Lights", "swimming_pool")
add("switch.swimming_pool_exhaust_fan", "Swimming Pool Exhaust Fan", "swimming_pool")
add("switch.swimming_pool_pool_camera_wiper", "Pool Camera Wiper", "swimming_pool")
add("binary_sensor.swimming_pool_motion", "Swimming Pool Motion", "swimming_pool")
add("media_player.swimming_pool", "Swimming Pool", "swimming_pool")
add("media_player.swimming_pool_2", "Swimming Pool")
add("media_player.swimming_pool_speakers", "Lounge and Swimming Pool Speakers")
add("vacuum.swimming_pool_pool_robot", "Pool Robot", "swimming_pool")
add("automation.pool_exhaust_fan_humidity_control", "Pool Exhaust Fan - Humidity Control", "swimming_pool")
add("media_player.plex", "Plex")

# ---- generic filler: look-alikes and other domains
for i, (aid, an) in enumerate(areas):
    if aid in ("kitchen", "swimming_pool"):
        continue
    add("light.%s_lamp_1" % aid, "%s Lamp 1" % an, aid) if aid != "guest_room" else None
    add("switch.%s_fan" % aid, "%s Fan" % an, aid)
    add("sensor.%s_temperature" % aid, "%s Temperature" % an, aid)
    add("binary_sensor.%s_motion" % aid, "%s Motion" % an, aid)
for n in range(1, 7):
    add("switch.smart_plug_%d" % n, "Smart Plug %d" % n)
    add("sensor.example_sensor_%d" % n, "Example Sensor %d" % n)
for n in range(1, 4):
    add("media_player.speaker_%d" % n, "Speaker %d" % n)
add("lock.front_door", "Front Door Lock", "hallway")
add("cover.garage_door", "Garage Door", "garage")
add("weather.home", "Home Weather")
add("sensor.nws_station_temperature", "NWS Station Temperature")
add("light.porch_light", "Porch Light", "garden")
add("fan.stairway_fan", "Stairway Fan", "hallway")

seen, uniq = set(), []
for e in E:
    if e["entity_id"] not in seen:
        seen.add(e["entity_id"]); uniq.append(e)
print(json.dumps({"_readme": "Synthetic test home generated by make_synthetic_snapshot.py. Not a real household.",
                  "entities": uniq, "areas": [{"area_id": a, "name": n, "aliases": []} for a, n in areas]}, indent=1))
